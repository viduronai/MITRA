from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import ForeignKey, Integer, SmallInteger, String, Text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from mitra_core.models.base import Base, Timestamps, pg_enum
from mitra_core.models.enums import (
    CallDirection,
    CallRating,
    CallResult,
    CallStatus,
    Locale,
    Sentiment,
)


class Call(Timestamps, Base):
    """One real call handled by an employee (TRD §10 ``call``).

    The id is generated by the voice service, so call start/end reports are idempotent. The
    transcript is stored inline as JSON for now; ``recording_uri`` / ``transcript_uri`` point
    at object storage (S3 Mumbai) once recordings exist. ``transcript_text`` is a lowercased
    flat copy for search (TODO: Postgres FTS / trigram index when volume needs it).
    The caller's number is never stored: ``contact`` holds its HMAC; ``phone_last4`` is display.
    """

    __tablename__ = "call"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    business_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("business.id", ondelete="CASCADE"), index=True
    )
    employee_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("employee.id", ondelete="SET NULL"), index=True
    )
    # Erasure ("forget this customer") deletes the contact and, by cascade, their calls.
    contact_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("contact.id", ondelete="CASCADE"), index=True
    )
    direction: Mapped[CallDirection] = mapped_column(pg_enum(CallDirection, "call_direction"))
    status: Mapped[CallStatus] = mapped_column(pg_enum(CallStatus, "call_status"))
    phone_last4: Mapped[str | None] = mapped_column(String(4))
    external_ref: Mapped[str | None] = mapped_column(String(64))
    language: Mapped[Locale | None] = mapped_column(pg_enum(Locale, "locale"))
    started_at: Mapped[datetime]
    ended_at: Mapped[datetime | None]
    duration_seconds: Mapped[int | None] = mapped_column(Integer)
    result: Mapped[CallResult | None] = mapped_column(pg_enum(CallResult, "call_result"))
    summary: Mapped[str | None] = mapped_column(String(800))
    next_step: Mapped[str | None] = mapped_column(String(300))
    sentiment: Mapped[Sentiment | None] = mapped_column(pg_enum(Sentiment, "call_sentiment"))
    fields: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default="{}", default=dict)
    transcript: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB, server_default="[]", default=list
    )
    transcript_text: Mapped[str] = mapped_column(Text, server_default="", default="")
    recording_uri: Mapped[str | None] = mapped_column(String(1024))
    transcript_uri: Mapped[str | None] = mapped_column(String(1024))
    latency_stats: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default="{}", default=dict)
    usage: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default="{}", default=dict)
    unknown_questions: Mapped[list[str]] = mapped_column(JSONB, server_default="[]", default=list)
    alerts: Mapped[list[dict[str, Any]]] = mapped_column(JSONB, server_default="[]", default=list)
    rating: Mapped[CallRating | None] = mapped_column(pg_enum(CallRating, "call_rating"))
    rating_reason: Mapped[str | None] = mapped_column(String(300))
    rated_by: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("app_user.id", ondelete="SET NULL")
    )
    rated_at: Mapped[datetime | None]
    processed_at: Mapped[datetime | None]


class CallAction(Base):
    """Something the employee did during the call (a tool call): booked, sent WhatsApp, ..."""

    __tablename__ = "call_action"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=uuid.uuid4)
    business_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("business.id", ondelete="CASCADE"), index=True
    )
    call_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("call.id", ondelete="CASCADE"), index=True
    )
    seq: Mapped[int] = mapped_column(SmallInteger)
    name: Mapped[str] = mapped_column(String(64))
    args: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default="{}", default=dict)
    result: Mapped[dict[str, Any]] = mapped_column(JSONB, server_default="{}", default=dict)
    ok: Mapped[bool]
    created_at: Mapped[datetime]
