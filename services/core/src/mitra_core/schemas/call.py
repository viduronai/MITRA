"""Calls: internal ingest from the voice service, and the owner-facing read/rate API."""

from __future__ import annotations

import json
import uuid
from datetime import datetime
from typing import Annotated, Any, Literal

from pydantic import AfterValidator, Field, StringConstraints

from mitra_core.models.enums import (
    CallDirection,
    CallRating,
    CallResult,
    CallStatus,
    Locale,
    Sentiment,
)
from mitra_core.schemas.common import E164Phone, RequestModel, ResponseModel

Text300 = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=300)]
FieldKey = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=60)]
FieldValue = Annotated[str, StringConstraints(strip_whitespace=True, max_length=300)]
ActionName = Annotated[str, StringConstraints(pattern=r"^[a-z][a-z0-9_]{0,63}$")]

MAX_TURNS = 400
MAX_ACTIONS = 100


_MAX_JSON_BYTES = 8_000


def _small_json(value: dict[str, Any]) -> dict[str, Any]:
    if len(json.dumps(value, default=str)) > _MAX_JSON_BYTES:
        raise ValueError(f"object too large (max {_MAX_JSON_BYTES} bytes as JSON)")
    return value


SmallJson = Annotated[dict[str, Any], AfterValidator(_small_json)]


# --- internal ingest (voice -> core) --------------------------------------------------------------


class CallStartIn(RequestModel):
    """Sent by the voice service when a call connects. ``id`` is generated by the caller."""

    id: uuid.UUID
    employee_id: uuid.UUID
    direction: CallDirection = CallDirection.WEB
    started_at: datetime
    caller_phone: E164Phone | None = None
    language: Locale | None = None
    external_ref: Annotated[str, StringConstraints(max_length=64)] | None = None


class MemoryItem(ResponseModel):
    key: str
    value: str
    status: Literal["confirmed", "inferred"]


class CallerCard(ResponseModel):
    """What the employee may know about a returning caller (CALL-14, WORKFLOWS §3 step 3)."""

    contact_id: uuid.UUID
    name: str | None
    language: Locale | None
    returning: bool
    memory: list[MemoryItem]
    recent_summaries: list[str]
    open_commitments: list[str]


class CallStartOut(ResponseModel):
    id: uuid.UUID
    status: CallStatus
    caller: CallerCard | None = None


class TranscriptTurnIn(RequestModel):
    role: Literal["user", "assistant"]
    text: Annotated[str, StringConstraints(max_length=4_000)]
    interrupted: bool = False
    at_ms: Annotated[int, Field(ge=0)] | None = None


class ActionIn(RequestModel):
    name: ActionName
    args: SmallJson = Field(default_factory=dict)
    result: SmallJson = Field(default_factory=dict)


class CallEndIn(RequestModel):
    employee_id: uuid.UUID
    ended_at: datetime
    transcript: list[TranscriptTurnIn] = Field(default_factory=list, max_length=MAX_TURNS)
    actions: list[ActionIn] = Field(default_factory=list, max_length=MAX_ACTIONS)
    language: Locale | None = None
    languages: list[Locale] = Field(default_factory=list, max_length=10)
    # Optional hints from the live call; post-call processing derives them when absent.
    result: CallResult | None = None
    fields: dict[FieldKey, FieldValue] = Field(default_factory=dict, max_length=40)
    unknown_questions: list[Text300] = Field(default_factory=list, max_length=20)
    latency_stats: SmallJson = Field(default_factory=dict)
    usage: SmallJson = Field(default_factory=dict)
    recording_uri: Annotated[str, StringConstraints(max_length=1024)] | None = None
    transcript_uri: Annotated[str, StringConstraints(max_length=1024)] | None = None


class CallEndOut(ResponseModel):
    id: uuid.UUID
    status: CallStatus
    replayed: bool = False


# --- owner-facing --------------------------------------------------------------------------------


class TranscriptLine(ResponseModel):
    speaker: Literal["employee", "caller"]
    text: str
    interrupted: bool = False
    at_ms: int | None = None


class ActionOut(ResponseModel):
    name: str
    args: dict[str, Any]
    result: dict[str, Any]
    ok: bool
    label: str


class AlertOut(ResponseModel):
    kind: Literal["hot_lead", "angry", "urgent", "failed_action", "unknown_question"]
    message: str


class CallRow(ResponseModel):
    id: uuid.UUID
    employee_id: uuid.UUID | None
    employee_name: str | None
    contact_id: uuid.UUID | None
    contact_name: str | None
    phone_last4: str | None
    direction: CallDirection
    status: CallStatus
    language: Locale | None
    started_at: datetime
    duration_seconds: int | None
    result: CallResult | None
    summary: str | None
    rating: CallRating | None


class CallList(ResponseModel):
    items: list[CallRow]
    total: int


class CallDetail(CallRow):
    ended_at: datetime | None
    next_step: str | None
    sentiment: Sentiment | None
    fields: dict[str, Any]
    transcript: list[TranscriptLine]
    actions: list[ActionOut]
    alerts: list[AlertOut]
    unknown_questions: list[str]
    recording_uri: str | None
    rating_reason: str | None
    latency_stats: dict[str, Any]


class RatingIn(RequestModel):
    rating: CallRating
    reason: Text300 | None = None


class RatingOut(ResponseModel):
    id: uuid.UUID
    rating: CallRating
    rating_reason: str | None
    rated_at: datetime


# --- Home ----------------------------------------------------------------------------------------


class HomeStats(ResponseModel):
    calls_today: int
    booked_today: int
    rescued_today: int
    needs_you: int
    live_now: int


class NeedsYouItem(ResponseModel):
    call_id: uuid.UUID
    kind: str
    message: str
    contact_name: str | None
    phone_last4: str | None
    at: datetime


class HomeSummary(ResponseModel):
    date: str
    timezone: str
    has_calls: bool
    stats: HomeStats
    needs_you: list[NeedsYouItem]
    recent_calls: list[CallRow]
